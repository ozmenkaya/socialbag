import { AgentToolInterface } from '@gitroom/nestjs-libraries/chat/agent.tool.interface';
import { createTool } from '@mastra/core/tools';
import { Injectable } from '@nestjs/common';
import sharp from 'sharp';
import z from 'zod';
import { checkAuth } from '@gitroom/nestjs-libraries/chat/auth.context';
import {
  DESIGN_TEMPLATES,
  DesignTemplate,
  DesignTemplatesService,
} from '@gitroom/nestjs-libraries/design-templates/design.templates.service';

const details = z.object({
  id: z.string(),
  path: z.string(),
});

@Injectable()
export class DesignTemplateTool implements AgentToolInterface {
  constructor(private _designTemplatesService: DesignTemplatesService) {}
  name = 'designTemplateTool';

  run() {
    return createTool({
      id: 'designTemplateTool',
      description: `Design a post picture from the customer's own photos with a brand template: free and instant, nothing is generated by AI, the photos stay real.
Prefer it over generateImageTool for posts of a project. Pass projectId (projectsListTool) to use the project's logo, colors, font and contact line.
Templates:
${Object.entries(DESIGN_TEMPLATES)
  .map(([name, text]) => `- ${name}: ${text}`)
  .join('\n')}
Keep the headline short (3 to 8 words), the subline to one line. Write them in the language of the customer's posts.
The design is saved in the media library and returned with the picture so you can check it.`,
      mcp: {
        annotations: {
          title: 'Design From Template',
          readOnlyHint: false,
          destructiveHint: false,
          idempotentHint: false,
          openWorldHint: false,
        },
      },
      inputSchema: z.object({
        template: z
          .enum(Object.keys(DESIGN_TEMPLATES) as [DesignTemplate, ...DesignTemplate[]])
          .describe('See the list of templates'),
        mediaIds: z
          .array(z.string())
          .min(1)
          .max(4)
          .describe('Photos (mediaListTool), one for every template but collage which takes 2 to 4'),
        size: z
          .enum(['square', 'portrait', 'story', 'landscape'])
          .describe('square 1:1, portrait 4:5 (feed posts), story 9:16 (stories, reels), landscape 16:9'),
        headline: z.string().min(1).max(120),
        subline: z.string().max(160).optional(),
        badge: z
          .string()
          .max(40)
          .optional()
          .describe('Short highlight like "Son 5 daire" or "3+1 · 145 m²", a round badge on the badge template and a small tag on the others'),
        contact: z
          .string()
          .max(120)
          .optional()
          .describe("Replaces the project's contact line, an empty string removes it"),
        projectId: z.string().optional().describe('Project (projectsListTool) whose brand is used'),
        primary: z
          .string()
          .regex(/^#[0-9a-fA-F]{6}$/)
          .optional()
          .describe("Replaces the brand's main color for this design, like #1F2A44"),
        accent: z
          .string()
          .regex(/^#[0-9a-fA-F]{6}$/)
          .optional()
          .describe("Replaces the brand's accent color for this design"),
        folderId: z
          .string()
          .optional()
          .describe('Folder id (mediaFoldersListTool) to save the design in'),
      }),
      // structuredContent carries the media, content the picture itself (same
      // as mediaViewTool)
      outputSchema: details.partial().extend({
        error: z.string().optional(),
        structuredContent: details.partial().optional(),
        content: z.array(z.any()).optional(),
      }),
      execute: async (inputData, context) => {
        checkAuth(inputData, context);
        const organizationId = JSON.parse(
          (context?.requestContext as any)?.get('organization') as string
        ).id;

        try {
          const { media, image } = await this._designTemplatesService.design(
            organizationId,
            inputData
          );
          const preview = await sharp(image)
            .resize(1024, 1024, { fit: 'inside' })
            .jpeg({ quality: 80 })
            .toBuffer();
          const saved = { id: media.id, path: media.path };

          return {
            structuredContent: saved,
            content: [
              { type: 'image', data: preview.toString('base64'), mimeType: 'image/jpeg' },
              { type: 'text', text: JSON.stringify(saved) },
            ],
          };
        } catch (err) {
          return {
            error: `The design failed: ${err instanceof Error ? err.message : String(err)}`,
          };
        }
      },
    });
  }
}
